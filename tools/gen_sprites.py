"""Generate the firmware's run-length-encoded sprites from tools/sprites/*.png.

    uv run tools/gen_sprites.py            # (re)write the generated C
    uv run tools/gen_sprites.py --check    # exit 1 if the committed C is stale

Reads every tools/sprites/<name>.png (1-bit, black = ink) and writes
main/sprite_data.c plus include/sprite_data.h: one `const sprite_t` per PNG,
named SPRITE_<NAME> from the file name. The PNG is the asset; the C is never
edited by hand, and --check (run by test_gen_sprites) fails when the two
disagree, so an edited PNG cannot ship without its regenerated data.

    uv run tools/gen_sprites.py --override-dir sprites.local --c-out <path>

merges private art over the templates: a <slot>.png in the override directory
replaces the template of the same name. A slot is fixed in name and size (the
screen layouts are built around the art), so a file that names no slot, or
whose width and height differ from the template's, is refused with the file,
the expected and the actual size. main/CMakeLists.txt runs this into the build
directory (with --no-header, so the source tree's header is never touched)
when sprites.local/ holds PNGs; the committed C never contains overrides, and
--check ignores them. Any file there whose name ends in .png in any letter
case but is not [a-z0-9_]+.png (charge.PNG, my art.png) is refused rather than
skipped, so a misnamed override cannot silently leave the template in.

Encoding (decoded by main/sprite.c, described in include/sprite.h): the
whole image as ONE row-major scan, runs alternating colour and starting with
BACKGROUND (a leading zero-length run when the first pixel is ink), one byte
per run. A run longer than 255 is written 255, 0, <rest>: the zero-length
opposite run lets the same colour continue. Runs wrap across rows.

The generated files must be clang-format clean as generated, so --check can
compare bytes: the byte array sits between clang-format off/on markers (the
formatter would otherwise re-pack it), and everything else is written in the
shape clang-format already produces.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SPRITES = os.path.join(ROOT, "tools", "sprites")
DEFAULT_C = os.path.join(ROOT, "main", "sprite_data.c")
DEFAULT_H = os.path.join(ROOT, "include", "sprite_data.h")

BANNER = "/* Generated by tools/gen_sprites.py from the PNGs in %s -- do not edit. */\n"
FILE_RE = re.compile(r"^[a-z0-9_]+\.png$")
BYTES_PER_LINE = 16
MAX_RLE_LEN = 0xFFFF  # sprite_t.rle_len is a uint16_t
MAX_DIM = 0xFFFF  # sprite_t.w and .h are uint16_t


def load_png(path):
    """Return (w, h, pixels) with pixels row-major, 1 = ink (black)."""
    with Image.open(path) as im:
        if im.mode != "1":
            raise ValueError("%s: expected a 1-bit PNG, got mode %r" % (path, im.mode))
        w, h = im.size
        return w, h, [1 if im.getpixel((x, y)) == 0 else 0 for y in range(h) for x in range(w)]


def encode(w, h, px):
    """Pixels (1 = ink) to the RLE byte list. See the module docstring."""
    assert len(px) == w * h
    out = []
    colour = 0  # the first run is background
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == colour:
            j += 1
        n = j - i
        while n > 255:
            out += [255, 0]
            n -= 255
        out.append(n)
        # the 255,0 pairs above end on the zero-length OPPOSITE run, which
        # the decoder reads as a colour flip back; the final byte is the
        # remainder in the original colour
        colour ^= 1
        i = j
    return out


def decode(w, h, rle):
    """Inverse of encode(); same semantics as main/sprite.c (used by the tests).

    A stream that ends early leaves the rest background; one that runs past
    w*h is clamped to w*h.
    """
    px = []
    colour = 0
    for n in rle:
        px += [colour] * n
        colour ^= 1
    px = px[: w * h]
    return px + [0] * (w * h - len(px))


def list_pngs(d):
    """The regular files in d whose lower-cased name ends in .png, sorted.

    The extension is matched case-insensitively so that `charge.PNG` is seen
    and refused by ident() rather than silently skipped (and the template
    shipped unknowingly). Directories, even ones named x.png, are not files.
    """
    return sorted(f for f in os.listdir(d) if f.lower().endswith(".png") and os.path.isfile(os.path.join(d, f)))


def ident(path):
    """The C identifier stem of a PNG; refuses anything but [a-z0-9_]+.png."""
    base = os.path.basename(path)
    if not FILE_RE.match(base):
        sys.exit("gen_sprites: %s: the file name must match [a-z0-9_]+.png (lower case, no spaces)" % path)
    return base[: -len(".png")]


def check_limits(f, w, h, rle):
    """Fail loudly when a sprite does not fit sprite_t's uint16_t fields."""
    if w > MAX_DIM or h > MAX_DIM:
        sys.exit("gen_sprites: %s: %dx%d does not fit sprite_t.w/.h (uint16_t)" % (f, w, h))
    if len(rle) > MAX_RLE_LEN:
        sys.exit("gen_sprites: %s: %d RLE bytes does not fit sprite_t.rle_len (uint16_t)" % (f, len(rle)))


def banner_dir(sprites_dir):
    """The source directory as the banner names it: repo-relative when inside the repo."""
    rel = os.path.relpath(os.path.abspath(sprites_dir), ROOT)
    if rel == ".." or rel.startswith(".." + os.sep):
        return os.path.abspath(sprites_dir)
    return rel.replace(os.sep, "/")


def render(sprites, src="tools/sprites", c_src=None):
    """sprites: list of (name, w, h, rle). Returns (c_text, h_text).

    The header's banner always names `src`: it does not depend on overrides.
    The C's banner names `c_src` when given (an override build says so).
    """
    banner = BANNER % src
    hdr = [banner, "#pragma once\n", '#include "sprite.h"\n\n']
    banner = BANNER % c_src if c_src else banner
    for name, _w, _h, _rle in sprites:
        hdr.append("extern const sprite_t SPRITE_%s;\n" % name.upper())
    c = [banner, '#include "sprite_data.h"\n']
    for name, w, h, rle in sprites:
        c.append("\n")
        c.append("// clang-format off\n")
        c.append("static const uint8_t %s_rle[] = {\n" % name)
        for k in range(0, len(rle), BYTES_PER_LINE):
            c.append("    " + ", ".join(str(b) for b in rle[k : k + BYTES_PER_LINE]) + ",\n")
        c.append("};\n")
        c.append("// clang-format on\n\n")
        c.append("const sprite_t SPRITE_%s = {%d, %d, %s_rle, %d};\n" % (name.upper(), w, h, name, len(rle)))
    return "".join(c), "".join(hdr)


def load_slots(sprites_dir):
    """The templates: {slot name: (file, w, h, pixels)}."""
    slots = {}
    for f in list_pngs(sprites_dir):
        path = os.path.join(sprites_dir, f)
        try:
            w, h, px = load_png(path)
        except ValueError as e:
            sys.exit("gen_sprites: %s" % e)
        slots[ident(path)] = (f, w, h, px)
    return slots


def merge_overrides(slots, override_dir):
    """Replace templates by same-named PNGs in override_dir.

    Returns the overridden slot names, sorted. A slot is fixed in name and
    size: every layout is built around its art, so an override that names no
    slot, or whose w x h differs from the template's, is refused.
    """
    if not os.path.isdir(override_dir):
        sys.exit("gen_sprites: --override-dir %s is not a directory" % override_dir)
    replaced = []
    for f in list_pngs(override_dir):
        path = os.path.join(override_dir, f)
        name = ident(path)
        if name not in slots:
            sys.exit(
                "gen_sprites: %s: no such sprite slot %r (slots: %s); rename the file to a slot"
                % (path, name, ", ".join(sorted(slots)))
            )
        try:
            w, h, px = load_png(path)
        except ValueError as e:
            sys.exit("gen_sprites: %s" % e)
        _tf, tw, th, _tpx = slots[name]
        if (w, h) != (tw, th):
            sys.exit(
                "gen_sprites: %s: slot %r is %dx%d, this file is %dx%d; an override must match its template's size"
                % (path, name, tw, th, w, h)
            )
        slots[name] = (f, w, h, px)
        replaced.append(name)
    return replaced


def build(sprites_dir, override_dir=None):
    """Returns (c_text, h_text, overridden slot names)."""
    slots = load_slots(sprites_dir)
    replaced = merge_overrides(slots, override_dir) if override_dir else []
    sprites = []
    for name, (f, w, h, px) in slots.items():
        rle = encode(w, h, px)
        check_limits(f, w, h, rle)
        sprites.append((name, w, h, rle))
    src = banner_dir(sprites_dir)
    c_src = "%s + %s overrides" % (src, banner_dir(override_dir)) if replaced else None
    c_text, h_text = render(sprites, src, c_src)
    return c_text, h_text, replaced


def read(path):
    try:
        with open(path) as f:
            return f.read()
    except FileNotFoundError:
        return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if the C is stale")
    ap.add_argument("--sprites-dir", default=DEFAULT_SPRITES)
    ap.add_argument("--c-out", default=DEFAULT_C)
    ap.add_argument("--h-out", default=DEFAULT_H)
    ap.add_argument(
        "--no-header",
        action="store_true",
        help="write only the C (the firmware build uses this, so a build never touches include/sprite_data.h)",
    )
    ap.add_argument(
        "--override-dir",
        help="merge <slot>.png files from this directory over the templates "
        "(same name and size as the template); ignored by --check",
    )
    args = ap.parse_args(argv)

    # --check compares the committed files against the TEMPLATES: overrides
    # are private and never reach the committed C
    override = None if args.check else args.override_dir
    c_text, h_text, replaced = build(args.sprites_dir, override)
    outputs = [(args.c_out, c_text)]
    if not (args.no_header and not args.check):
        outputs.append((args.h_out, h_text))

    if args.check:
        stale = [p for p, t in outputs if read(p) != t]
        for p in stale:
            print("gen_sprites: %s is stale or missing; run `uv run tools/gen_sprites.py`" % p, file=sys.stderr)
        return 1 if stale else 0

    if override:
        print("gen_sprites: overridden slots: %s" % (", ".join(replaced) if replaced else "(none)"))
    for p, t in outputs:
        # an unchanged file is left alone, so a build that regenerates the C
        # does not touch the header and recompile everything that includes it
        if read(p) == t:
            continue
        with open(p, "w") as f:
            f.write(t)
        print("wrote %s" % os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
