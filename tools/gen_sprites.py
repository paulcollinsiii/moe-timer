"""Generate the firmware's run-length-encoded sprites from tools/sprites/*.png.

    uv run tools/gen_sprites.py            # (re)write the generated C
    uv run tools/gen_sprites.py --check    # exit 1 if the committed C is stale

Reads every tools/sprites/<name>.png (1-bit, black = ink) and writes
main/sprite_data.c plus include/sprite_data.h: one `const sprite_t` per PNG,
named SPRITE_<NAME> from the file name. The PNG is the asset; the C is never
edited by hand, and --check (run by test_gen_sprites) fails when the two
disagree, so an edited PNG cannot ship without its regenerated data.

A slot may have more than one picture. <slot>.png is variant 0 and
<slot>.1.png, <slot>.2.png ... are variants 1, 2 ...: numbered without a gap,
without leading zeros, and each exactly the size of <slot>.png (the layouts
use SPRITE_<NAME>.w/.h and literals such as TIMESUP_COL_X, so a variant of
another size is refused with the file and both sizes). Per slot the C also
holds the table `SPRITE_<NAME>_VARIANTS[]` (index = variant number) and
`SPRITE_<NAME>_VARIANT_COUNT`; the lock screens pick one per lock episode
(main/sprite_pick.c).

    uv run tools/gen_sprites.py --override-dir sprites.local --c-out <path>

merges private art over the templates, file by file: <slot>.png replaces
variant 0, and <slot>.<n>.png replaces the template's variant n or, when the
template has no variant n, adds it. Template variants the override directory
does not name stay, so dropping sprites.local/charge.1.png gives the charge
screen the template art plus that one extra; to show ONLY your own art for a
slot, override every variant the template has. A slot is fixed in name and
size (the screen layouts are built around the art), so a file that names no
slot, or whose width and height differ from the slot's base image, is refused
with the file, the expected and the actual size. The numbering is checked
after the merge. main/CMakeLists.txt runs this into the build
directory (with --no-header, so the source tree's header is never touched)
when sprites.local/ holds PNGs; the committed C never contains overrides, and
--check ignores them. Any file there whose name ends in .png in any letter
case but is not <slot>.png or <slot>.<n>.png (charge.PNG, my art.png,
charge.0.png) is refused rather than skipped, so a misnamed override cannot silently leave the template in.

Encoding (decoded by main/sprite.c, described in include/sprite.h): the
whole image as ONE row-major scan, runs alternating colour and starting with
BACKGROUND (a leading zero-length run when the first pixel is ink), one byte
per run. A run longer than 255 is written 255, 0, <rest>: the zero-length
opposite run lets the same colour continue. Runs wrap across rows.

The generated files must be clang-format clean as generated, so --check can
compare bytes: the byte array sits between clang-format off/on markers (the
formatter would otherwise re-pack it), and everything else is written in the
shape clang-format already produces.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SPRITES = os.path.join(ROOT, "tools", "sprites")
DEFAULT_C = os.path.join(ROOT, "main", "sprite_data.c")
DEFAULT_H = os.path.join(ROOT, "include", "sprite_data.h")

BANNER = "/* Generated by tools/gen_sprites.py from the PNGs in %s -- do not edit. */\n"
FILE_RE = re.compile(r"^([a-z0-9_]+)(?:\.([1-9][0-9]*))?\.png$")
MAX_VARIANT = 254  # the variant index and count are uint8_t on the device (sprite_pick.h)
BYTES_PER_LINE = 16
MAX_RLE_LEN = 0xFFFF  # sprite_t.rle_len is a uint16_t
MAX_DIM = 0xFFFF  # sprite_t.w and .h are uint16_t


def load_png(path):
    """Return (w, h, pixels) with pixels row-major, 1 = ink (black)."""
    with Image.open(path) as im:
        if im.mode != "1":
            raise ValueError("%s: expected a 1-bit PNG, got mode %r" % (path, im.mode))
        w, h = im.size
        return w, h, [1 if im.getpixel((x, y)) == 0 else 0 for y in range(h) for x in range(w)]


def encode(w, h, px):
    """Pixels (1 = ink) to the RLE byte list. See the module docstring."""
    assert len(px) == w * h
    out = []
    colour = 0  # the first run is background
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == colour:
            j += 1
        n = j - i
        while n > 255:
            out += [255, 0]
            n -= 255
        out.append(n)
        # the 255,0 pairs above end on the zero-length OPPOSITE run, which
        # the decoder reads as a colour flip back; the final byte is the
        # remainder in the original colour
        colour ^= 1
        i = j
    return out


def decode(w, h, rle):
    """Inverse of encode(); same semantics as main/sprite.c (used by the tests).

    A stream that ends early leaves the rest background; one that runs past
    w*h is clamped to w*h.
    """
    px = []
    colour = 0
    for n in rle:
        px += [colour] * n
        colour ^= 1
    px = px[: w * h]
    return px + [0] * (w * h - len(px))


def list_pngs(d):
    """The regular files in d whose lower-cased name ends in .png, sorted.

    The extension is matched case-insensitively so that `charge.PNG` is seen
    and refused by parse_name() rather than silently skipped (and the template
    shipped unknowingly). Directories, even ones named x.png, are not files.
    """
    return sorted(f for f in os.listdir(d) if f.lower().endswith(".png") and os.path.isfile(os.path.join(d, f)))


def parse_name(path):
    """(slot, n) of a PNG: n is 0 for <slot>.png and k for <slot>.<k>.png.

    Refuses anything else, including .0, a leading zero and a second dot, so
    a misnamed variant is an error rather than a silently missing sprite.
    """
    base = os.path.basename(path)
    m = FILE_RE.match(base)
    if not m:
        sys.exit(
            "gen_sprites: %s: the file name must match <slot>.png or <slot>.<n>.png, with the slot in "
            "[a-z0-9_]+ (lower case, no spaces) and n a positive number without leading zeros" % path
        )
    n = int(m.group(2)) if m.group(2) else 0
    if n > MAX_VARIANT:
        sys.exit("gen_sprites: %s: variant numbers go up to %d" % (path, MAX_VARIANT))
    return m.group(1), n


def check_limits(f, w, h, rle):
    """Fail loudly when a sprite does not fit sprite_t's uint16_t fields."""
    if w > MAX_DIM or h > MAX_DIM:
        sys.exit("gen_sprites: %s: %dx%d does not fit sprite_t.w/.h (uint16_t)" % (f, w, h))
    if len(rle) > MAX_RLE_LEN:
        sys.exit("gen_sprites: %s: %d RLE bytes does not fit sprite_t.rle_len (uint16_t)" % (f, len(rle)))


def banner_dir(sprites_dir):
    """The source directory as the banner names it: repo-relative when inside the repo."""
    rel = os.path.relpath(os.path.abspath(sprites_dir), ROOT)
    if rel == ".." or rel.startswith(".." + os.sep):
        return os.path.abspath(sprites_dir)
    return rel.replace(os.sep, "/")


def render(sprites, src="tools/sprites", c_src=None):
    """sprites: list of (name, w, h, [rle, ...]), one stream per variant with
    variant 0 (<name>.png) first. Returns (c_text, h_text).

    The header's banner always names `src`: it does not depend on overrides,
    and neither does the header (the count is a const the C defines, so an
    override that adds a variant changes the C and never the header). The C's
    banner names `c_src` when given (an override build says so).

    Per slot the C holds SPRITE_<NAME> (variant 0, extern: existing code
    names it), the other variants as file-static SPRITE_<NAME>_VARIANT_<n>,
    and the table SPRITE_<NAME>_VARIANTS[] / SPRITE_<NAME>_VARIANT_COUNT that
    the lock screens pick from.
    """
    banner = BANNER % src
    hdr = [banner, "#pragma once\n", '#include "sprite.h"\n\n']
    banner = BANNER % c_src if c_src else banner
    seen = {}
    for name, _w, _h, rles in sprites:
        up = name.upper()
        for sym in [up, up + "_VARIANTS", up + "_VARIANT_COUNT"] + ["%s_VARIANT_%d" % (up, n) for n in range(1, len(rles))]:
            claim(seen, "SPRITE_" + sym, name)
        for n in range(len(rles)):
            claim(seen, "%s_rle" % (name if n == 0 else "%s_%d" % (name, n)), name)
        hdr.append("extern const sprite_t SPRITE_%s;\n" % up)
        hdr.append("extern const sprite_t *const SPRITE_%s_VARIANTS[];\n" % up)
        hdr.append("extern const unsigned SPRITE_%s_VARIANT_COUNT;\n" % up)
    c = [banner, '#include "sprite_data.h"\n']
    for name, w, h, rles in sprites:
        up = name.upper()
        for n, rle in enumerate(rles):
            stem = name if n == 0 else "%s_%d" % (name, n)
            c.append("\n")
            c.append("// clang-format off\n")
            c.append("static const uint8_t %s_rle[] = {\n" % stem)
            for k in range(0, len(rle), BYTES_PER_LINE):
                c.append("    " + ", ".join(str(b) for b in rle[k : k + BYTES_PER_LINE]) + ",\n")
            c.append("};\n")
            c.append("// clang-format on\n\n")
            if n == 0:
                c.append("const sprite_t SPRITE_%s = {%d, %d, %s_rle, %d};\n" % (up, w, h, stem, len(rle)))
            else:
                c.append(
                    "static const sprite_t SPRITE_%s_VARIANT_%d = {%d, %d, %s_rle, %d};\n" % (up, n, w, h, stem, len(rle))
                )
        refs = ["&SPRITE_%s" % up] + ["&SPRITE_%s_VARIANT_%d" % (up, n) for n in range(1, len(rles))]
        c.append("\n")
        if len(refs) == 1:
            c.append("const sprite_t *const SPRITE_%s_VARIANTS[] = {%s};\n" % (up, refs[0]))
        else:
            c.append("const sprite_t *const SPRITE_%s_VARIANTS[] = {\n" % up)
            c.extend("    %s,\n" % r for r in refs)
            c.append("};\n")
        c.append("const unsigned SPRITE_%s_VARIANT_COUNT = %d;\n" % (up, len(refs)))
    return "".join(c), "".join(hdr)


def claim(seen, symbol, slot):
    """Refuse two slots (or a slot and a variant) that would emit the same C name."""
    if symbol in seen and seen[symbol] != slot:
        sys.exit(
            "gen_sprites: slots %r and %r would both define %s; rename one" % (seen[symbol], slot, symbol)
        )
    if symbol in seen:
        sys.exit("gen_sprites: slot %r defines %s twice; rename it" % (slot, symbol))
    seen[symbol] = slot


def load_slots(sprites_dir):
    """The templates: {slot name: {n: (file, w, h, pixels)}}, n = 0 for <slot>.png.

    A variant is checked against its slot's base image; a slot with variants
    but no base is refused.
    """
    slots = {}
    paths = {}
    for f in list_pngs(sprites_dir):
        path = os.path.join(sprites_dir, f)
        name, n = parse_name(path)
        try:
            w, h, px = load_png(path)
        except ValueError as e:
            sys.exit("gen_sprites: %s" % e)
        slots.setdefault(name, {})[n] = (f, w, h, px)
        paths[(name, n)] = path
    for name, variants in slots.items():
        if 0 not in variants:
            first = paths[(name, min(variants))]
            sys.exit("gen_sprites: %s: slot %r has no %s.png, the base image every variant is sized by" % (first, name, name))
        _bf, bw, bh, _bpx = variants[0]
        for n, (_f, w, h, _px) in variants.items():
            if (w, h) != (bw, bh):
                sys.exit(variant_size_error(paths[(name, n)], name, bw, bh, w, h))
    return slots


def variant_size_error(path, name, bw, bh, w, h):
    return (
        "gen_sprites: %s: slot %r is %dx%d (its base image), this file is %dx%d; "
        "every variant must match its slot's base size" % (path, name, bw, bh, w, h)
    )


def merge_overrides(slots, override_dir):
    """Merge the PNGs of override_dir over the templates, per file.

    <slot>.png replaces variant 0, <slot>.<n>.png replaces the template's
    variant n when it has one and ADDS variant n when it does not. A template
    variant the override dir does not name stays. Returns the touched slot
    names, sorted. A slot is fixed in name and size: every layout is built
    around its art, so a file that names no slot, or whose w x h differs from
    the slot's base size, is refused. The numbering is checked after the
    merge (check_numbering), so an override can fill a template's gap.
    """
    if not os.path.isdir(override_dir):
        sys.exit("gen_sprites: --override-dir %s is not a directory" % override_dir)
    replaced = set()
    for f in list_pngs(override_dir):
        path = os.path.join(override_dir, f)
        name, n = parse_name(path)
        if name not in slots:
            sys.exit(
                "gen_sprites: %s: no such sprite slot %r (slots: %s); rename the file to a slot"
                % (path, name, ", ".join(sorted(slots)))
            )
        try:
            w, h, px = load_png(path)
        except ValueError as e:
            sys.exit("gen_sprites: %s" % e)
        _tf, tw, th, _tpx = slots[name][0]
        if (w, h) != (tw, th):
            if n == 0:
                sys.exit(
                    "gen_sprites: %s: slot %r is %dx%d, this file is %dx%d; an override must match its template's size"
                    % (path, name, tw, th, w, h)
                )
            sys.exit(variant_size_error(path, name, tw, th, w, h))
        slots[name][n] = (f, w, h, px)
        replaced.add(name)
    return sorted(replaced)


def check_numbering(slots, *dirs):
    """Refuse a slot whose variants skip a number (<slot>.png, then .1, .2, ...)."""
    where = " or ".join(banner_dir(d) for d in dirs if d)
    for name, variants in slots.items():
        for n in range(max(variants) + 1):
            if n not in variants:
                sys.exit(
                    "gen_sprites: slot %r has %s.%d.png but no %s.%d.png in %s; "
                    "variants are numbered 1, 2, 3 ... without a gap"
                    % (name, name, max(variants), name, n, where)
                )


def build(sprites_dir, override_dir=None):
    """Returns (c_text, h_text, overridden slot names)."""
    slots = load_slots(sprites_dir)
    replaced = merge_overrides(slots, override_dir) if override_dir else []
    check_numbering(slots, sprites_dir, override_dir)
    sprites = []
    for name, variants in slots.items():
        _f, w, h, _px = variants[0]
        rles = []
        for n in sorted(variants):
            f, vw, vh, px = variants[n]
            rle = encode(vw, vh, px)
            check_limits(f, vw, vh, rle)
            rles.append(rle)
        sprites.append((name, w, h, rles))
    src = banner_dir(sprites_dir)
    c_src = "%s + %s overrides" % (src, banner_dir(override_dir)) if replaced else None
    c_text, h_text = render(sprites, src, c_src)
    return c_text, h_text, replaced


def read(path):
    try:
        with open(path) as f:
            return f.read()
    except FileNotFoundError:
        return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if the C is stale")
    ap.add_argument("--sprites-dir", default=DEFAULT_SPRITES)
    ap.add_argument("--c-out", default=DEFAULT_C)
    ap.add_argument("--h-out", default=DEFAULT_H)
    ap.add_argument(
        "--no-header",
        action="store_true",
        help="write only the C (the firmware build uses this, so a build never touches include/sprite_data.h)",
    )
    ap.add_argument(
        "--override-dir",
        help="merge <slot>.png files from this directory over the templates "
        "(same name and size as the template); ignored by --check",
    )
    args = ap.parse_args(argv)

    # --check compares the committed files against the TEMPLATES: overrides
    # are private and never reach the committed C
    override = None if args.check else args.override_dir
    c_text, h_text, replaced = build(args.sprites_dir, override)
    outputs = [(args.c_out, c_text)]
    if not (args.no_header and not args.check):
        outputs.append((args.h_out, h_text))

    if args.check:
        stale = [p for p, t in outputs if read(p) != t]
        for p in stale:
            print("gen_sprites: %s is stale or missing; run `uv run tools/gen_sprites.py`" % p, file=sys.stderr)
        return 1 if stale else 0

    if override:
        print("gen_sprites: overridden slots: %s" % (", ".join(replaced) if replaced else "(none)"))
    for p, t in outputs:
        # an unchanged file is left alone, so a build that regenerates the C
        # does not touch the header and recompile everything that includes it
        if read(p) == t:
            continue
        with open(p, "w") as f:
            f.write(t)
        print("wrote %s" % os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
