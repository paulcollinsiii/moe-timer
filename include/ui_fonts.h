/* The five font sizes the screens draw with, behind one name each. Every
   label in display_screens.c takes its font from here, so a font set is
   switched in this header and nowhere else.

   The set is CONFIG_MAGTAG_FONT_SET_* (the Kconfig choice in
   main/Kconfig.projbuild; the host build defines the same macro from the
   MAGTAG_FONT_SET CMake variable). The default set is term; stock is LVGL's
   4 bpp Montserrat. The others are the 1 bpp fonts under main/fonts/<set>/,
   generated by tools/gen_fonts.py from the code points in ui_font_ranges.h;
   a set's sources are compiled only when it is selected. */
#ifndef UI_FONTS_H
#define UI_FONTS_H

#include "lvgl.h"

/* ui_font_<set>_<px>: the symbol a generated font defines. */
#define UI_FONT_SYM_(set, px) ui_font_##set##_##px
#define UI_FONT_SYM(set, px) UI_FONT_SYM_(set, px)

#if defined(CONFIG_MAGTAG_FONT_SET_MONT1)
#define UI_FONT_SET_NAME mont1
#elif defined(CONFIG_MAGTAG_FONT_SET_TERM)
#define UI_FONT_SET_NAME term
#elif defined(CONFIG_MAGTAG_FONT_SET_LIB)
#define UI_FONT_SET_NAME lib
#endif

#ifdef UI_FONT_SET_NAME
extern const lv_font_t UI_FONT_SYM(UI_FONT_SET_NAME, 12), UI_FONT_SYM(UI_FONT_SET_NAME, 16),
    UI_FONT_SYM(UI_FONT_SET_NAME, 18), UI_FONT_SYM(UI_FONT_SET_NAME, 28), UI_FONT_SYM(UI_FONT_SET_NAME, 48);
#define UI_FONT_12 (&UI_FONT_SYM(UI_FONT_SET_NAME, 12))
#define UI_FONT_16 (&UI_FONT_SYM(UI_FONT_SET_NAME, 16))
#define UI_FONT_18 (&UI_FONT_SYM(UI_FONT_SET_NAME, 18))
#define UI_FONT_28 (&UI_FONT_SYM(UI_FONT_SET_NAME, 28))
#define UI_FONT_48 (&UI_FONT_SYM(UI_FONT_SET_NAME, 48))
#else
#define UI_FONT_12 (&lv_font_montserrat_12)
#define UI_FONT_16 (&lv_font_montserrat_16)
#define UI_FONT_18 (&lv_font_montserrat_18)
#define UI_FONT_28 (&lv_font_montserrat_28)
#define UI_FONT_48 (&lv_font_montserrat_48)
#endif

#endif /* UI_FONTS_H */
