/* The five font sizes the screens draw with, behind one name each. Every
   label in display_screens.c takes its font from here.

   The fonts are the 1 bpp term set under main/fonts/ (Terminus at 12, 16
   and 18 px, Liberation Sans at 28 and 48), generated by tools/gen_fonts.py
   from the code points in ui_font_ranges.h. LVGL's default font is
   ui_font_term_12 as well (main/CMakeLists.txt on the device,
   test/mocks/lv_conf_host.h on the host); no stock Montserrat is built in. */
#ifndef UI_FONTS_H
#define UI_FONTS_H

#include "lvgl.h"

extern const lv_font_t ui_font_term_12, ui_font_term_16, ui_font_term_18, ui_font_term_28, ui_font_term_48;

#define UI_FONT_12 (&ui_font_term_12)
#define UI_FONT_16 (&ui_font_term_16)
#define UI_FONT_18 (&ui_font_term_18)
#define UI_FONT_28 (&ui_font_term_28)
#define UI_FONT_48 (&ui_font_term_48)

#endif /* UI_FONTS_H */
